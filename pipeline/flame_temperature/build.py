"""Flame temperature engine (suppress): entry point.

Reads PSI-69 (FLEX) and PSI-10 (ACME Flame Design, Normal Flame), plus PSI-39 (CFI) and
PSI-68 (FLEX-2) for the gap list, and writes the engine files into
data/modules/flame-temperature/. Written with SI assistance (Claude Code).

Run (from the repo root):
    uv run --python 3.12 --with-requirements pipeline/flame_temperature/requirements.txt \
        python pipeline/flame_temperature/build.py

At this stage (DOB-56) the command checks its inputs, loads the FLEX table, runs the reference
checks (exit 2 if one fails), writes flex_tests.json and flex_checks.json with all seven checks
(exit 3 if one fails), writes flex_grid.json, then flex_gaps.json and the helium column of
flex_grid.json (gaps.py; exit 4 if a table is missing or contradicts the coverage headline),
flex_doe.json (doe.py, the design-of-experiments checks) and the three hand-over files module.json, evidence.json and findings.json.
"""

import datetime
import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))  # lets build.py import its sibling modules

REPO = Path(__file__).resolve().parent.parent.parent
TABLES = REPO / "data/raw/tables"
FLEX_CSV = TABLES / "PSI-69_Experimental table_FLEX.csv"
PSI10_CSV = TABLES / "PSI-10_Experimental table_Flame Design_Normal Flame.csv"
OUT_DIR = REPO / "data/modules/flame-temperature"

# Cantera data files the physics needs: thermodynamics, and transport data for O2, N2, CO2, He.
CANTERA_FILES = ("nasa_gas.yaml", "example_data/ammonia-CO-H2-Alzueta-2023.yaml")

RESTORE_HINT = (
    "The tables are git-ignored on main. Restore one with:\n"
    '  git show "origin/alex/modal-train:data/raw/tables/<file name>" > "data/raw/tables/<file name>"'
)


def check_inputs() -> list[str]:
    """Return a list of problems; empty means every input is in place."""
    problems = []
    for table in (FLEX_CSV, PSI10_CSV, TABLES / "PSI-39_Experimental table_CFI.csv",
                  TABLES / "PSI-68_Experimental table_Flex2.csv"):
        if not table.is_file():
            problems.append(f"missing PSI table: {table.relative_to(REPO)}")
    try:
        import cantera as ct
    except ImportError:
        problems.append("cantera is not installed (see the run command in this file's docstring)")
        return problems
    for name in CANTERA_FILES:
        try:
            ct.Solution(name) if name.startswith("example_data") else ct.Species.list_from_file(name)
        except Exception as exc:  # Cantera raises its own CanteraError type
            problems.append(f"Cantera {ct.__version__} cannot load {name}: {exc}")
    return problems


PSI_LINKS = {
    "PSI-69": "https://psi.nasa.gov/geode-py/ws/repo/investigations/PSI-69",
    "PSI-10": "https://psi.nasa.gov/geode-py/ws/repo/investigations/PSI-10",
}
SI_NOTE = (
    "Generated by pipeline/flame_temperature/build.py, a script written with SI assistance "
    "(Claude Code, Anthropic). The humans chose the idea and the method."
)


def git_commit() -> str:
    """Short commit of the script, with '+local' when the tree has uncommitted changes."""
    try:
        sha = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=REPO, capture_output=True,
                             text=True, check=True).stdout.strip()
        dirty = subprocess.run(["git", "status", "--porcelain", "pipeline"], cwd=REPO,
                               capture_output=True, text=True, check=True).stdout.strip()
        return sha + ("+local" if dirty else "")
    except Exception:
        return "unknown"


def header(psi_ids: list[str], extra: dict | None = None) -> dict:
    """Header block shared by the generated files."""
    import cantera as ct
    import flex

    block = {
        "psi_ids": {i: PSI_LINKS[i] for i in psi_ids},
        "script": "pipeline/flame_temperature/build.py",
        "script_commit": git_commit(),
        "date": datetime.date.today().isoformat(),
        "cantera_version": ct.__version__,
        "co_column_assumption": flex.CO_ASSUMPTION,
        "si_note": SI_NOTE,
    }
    block.update(extra or {})
    return block


def write_json(name: str, payload: dict) -> Path:
    path = OUT_DIR / name
    path.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return path


def build_flex_tests(table) -> list[dict]:
    """Write flex_tests.json and assert what the issue (DOB-54) promises."""
    import flex

    rows = flex.tests_rows(table)
    assert len(rows) == 274, len(rows)
    with_numbers = [r for r in rows if r["ceiling_temperature_k"] is not None
                    and r["heat_spreading_m2_s"] is not None]
    assert len(with_numbers) == 273, len(with_numbers)
    dropped = [r for r in rows if r["flags"]["dropped"]]
    assert [r["flex_test"] for r in dropped] == [114]
    assert dropped[0]["ceiling_temperature_k"] is None and dropped[0]["heat_spreading_m2_s"] is None
    cold = flex.coldest(rows)
    for key, expected in flex.SPIKE_COLDEST_K.items():
        assert abs(cold[key] - expected) <= 2.0, (key, cold[key], expected)
    payload = {
        "header": header(["PSI-69"], {
            "units": {"pressure_atm": "atm", "d0_mm": "mm", "ceiling_temperature_k": "K",
                      "heat_spreading_m2_s": "m^2/s (gas alone, 1000 K)", "share_burned": "0 to 1",
                      "burning_rate_mm2_s": "mm^2/s", "burn_time_s": "s"},
            "ceiling_temperature": "adiabatic flame temperature, fuel burned completely in the gas, "
                                   "start 298.15 K, constant pressure and enthalpy equilibrium (Cantera)",
            "gas_label_rule": f"helium above {flex.ADDED_GAS_THRESHOLD} of the mixture, else carbon "
                              f"dioxide above {flex.ADDED_GAS_THRESHOLD}, else nitrogen only",
            "share_burned_rule": "1 - (diameter at flame-out / diameter at start)^3, clipped to 0..1; "
                                 "empty when either diameter is missing (flag incomplete)",
            "coldest_ceiling_temperature_k": {f"{f} / {g}": round(t, 1) for (f, g), t in sorted(cold.items())},
            "counts": {"rows": len(rows), "with_both_numbers": len(with_numbers),
                       "dropped": [r["flex_test"] for r in dropped],
                       "share_burned_known": sum(r["share_burned"] is not None for r in rows)},
        }),
        "tests": rows,
    }
    write_json("flex_tests.json", payload)
    return rows


def build_flex_checks(rows: list[dict]) -> tuple[bool, dict]:
    """Write flex_checks.json (all seven checks) and return True when every check passed."""
    import checks

    results = checks.all_checks(rows)
    sanity = checks.check_co2_lowers_temperature()
    for c in results:
        print(f"  {'PASS' if c['passed'] else 'FAIL'} {c['id']}: {c['result']}")
    payload = {
        "header": header(["PSI-69", "PSI-10"], {
            "random_seed": 0,
            "trial_run_note": "Each check lists the 14 Nov trial-run value under trial_run, for "
                              "comparison only. The numbers in 'result' come from this script.",
        }),
        "checks": results,
        "sanity": [sanity],
        "all_passed": all(c["passed"] for c in results) and sanity["passed"],
    }
    write_json("flex_checks.json", payload)
    return payload["all_passed"], payload


def build_flex_grid(rows: list[dict], checks_payload: dict) -> dict:
    """Write flex_grid.json (compact: one array per slider position) and return its summary."""
    import grid

    g = grid.build_grid(rows)
    link = next(c for c in checks_payload["checks"] if c["id"] == "fitted_link")
    payload = {
        "header": header(["PSI-69"], {
            "steps": {"fuel": grid.FUELS, "oxygen": "0.12 to 0.34, step 0.01",
                      "added_gas": "none; carbon dioxide 0.05 to 0.70 step 0.05; helium 0.05 to 0.45 "
                                   "step 0.05; nitrogen is the rest",
                      "pressure_atm": grid.PRESSURES_ATM,
                      "d0_mm": f"{grid.N_DIAMETERS} values evenly spaced across the FLEX range: {g['d0_values_mm']}",
                      "left_out": "positions where oxygen plus added gas is above 1"},
            "columns": g["columns"],
            "units": {"x_o2": "mole fraction", "x_added": "mole fraction", "pressure_atm": "atm",
                      "d0_mm": "mm", "ceiling_temperature_k": "K", "heat_spreading_m2_s": "m^2/s",
                      "share_burned_pred": "0 to 1"},
            "nearest": f"up to {grid.N_NEAREST} real tests of the same fuel as [flex_test, distance]; "
                       f"distance = sqrt(sum of squared differences each divided by its scale); scales "
                       f"{grid.SCALE}",
            "no_test_near": f"if the nearest real test differs by more than {grid.NO_TEST_NEAR_K} K in "
                            "ceiling temperature the position has no prediction (a proposal, to be tuned)",
            "prediction": "gradient-boosted trees (the fitted link), trained once on all eligible tests",
            "fitted_link_error_points": link["result"]["fitted_link"]["mean_abs_error_points"],
            "fitted_link_r2_unseen_days": link["result"]["fitted_link"]["r2"],
            "n_rows": g["n_rows"], "n_no_test_near": g["n_no_test_near"],
        }),
        "rows": g["rows"],
    }
    path = OUT_DIR / "flex_grid.json"
    path.write_text(json.dumps(payload, separators=(",", ":"), ensure_ascii=False) + "\n", encoding="utf-8")
    size = path.stat().st_size
    assert size < 3 * 1024 * 1024, f"flex_grid.json is {size} bytes, limit 3 MB"
    return {"rows": g["n_rows"], "no_test_near": g["n_no_test_near"], "bytes": size}


def main() -> int:
    problems = check_inputs()
    if problems:
        print("flame_temperature: cannot start", file=sys.stderr)
        for p in problems:
            print(f"  - {p}", file=sys.stderr)
        print(RESTORE_HINT, file=sys.stderr)
        return 1
    import cantera as ct

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    import flex

    table = flex.load()
    info = flex.summary(table)
    print(f"Cantera {ct.__version__}")
    print(f"found {FLEX_CSV.relative_to(REPO)}")
    print(f"found {PSI10_CSV.relative_to(REPO)}")
    print(f"FLEX rows read: {info['rows']}, usable: {info['usable']}, dropped tests: {info['dropped']}")
    print(f"complete tests (share of fuel burned known): {info['complete']}, incomplete: {info['incomplete']}")
    print(f"tests per gas label: {info['per_gas_label']}")
    print(f"share of fuel burned: {info['share_burned_min']:.3f} to {info['share_burned_max']:.3f}"
          f" (clipped tests: {info['share_clipped_tests']})")
    import checks
    import physics

    print("reference checks:")
    results = checks.run_reference_checks()
    for r in results:
        print(f"  {'PASS' if r['passed'] else 'FAIL'} {r['id']} (n={r['n']}): {r['result']}")
    if not all(r["passed"] for r in results):
        print("flame_temperature: a reference check failed, stopping", file=sys.stderr)
        return 2
    alpha = physics.heat_spreading_speed(0.21, 0.79, 0.0, 0.0, 1.0)
    print(f"example: heat-spreading speed of air at 1000 K, 1 atm = {alpha:.2e} m2/s")
    rows = build_flex_tests(table)
    print(f"wrote flex_tests.json: {len(rows)} rows")
    ok, checks_payload = build_flex_checks(rows)
    if not ok:
        print("flame_temperature: a check failed, see flex_checks.json", file=sys.stderr)
        return 3
    summary = build_flex_grid(rows, checks_payload)
    print(f"wrote flex_grid.json: {summary['rows']} positions, {summary['no_test_near']} flagged "
          f"no_test_near, {summary['bytes'] / 1e6:.2f} MB")
    import gaps

    try:
        g = gaps.write_outputs(OUT_DIR, TABLES)
    except (FileNotFoundError, ValueError) as exc:
        print(f"flame_temperature: gap list not written: {exc}", file=sys.stderr)
        return 4
    print(f"wrote flex_gaps.json: {g['gap_rows']} region cells ranked; {g['grid_flagged']} helium "
          f"grid rows flagged model_fails_here")
    import doe

    for cid in doe.write_outputs(OUT_DIR):
        print(f"wrote flex_doe.json: check {cid}")
    import handover

    counts = handover.write_all(OUT_DIR)
    print(f"wrote module.json, evidence.json ({counts['evidence']} records) and findings.json "
          f"({counts['findings']} records)")
    print(f"output folder ready: {OUT_DIR.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
