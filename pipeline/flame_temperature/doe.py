"""Design-of-experiments checks on the fitted link: flex_doe.json (DOB-115, DOB-114).

Two questions a test planner asks of a model, answered from the FLEX tests alone (PSI-69):

1. lack_of_fit: is the model as good as the data allows? Its error on unseen test days is set
   against the scatter between repeated tests ("pure error").
2. batch_replay: does picking tests as a spread-out batch teach the model faster than picking
   the top of a one-by-one ranking? One added gas is treated as never flown, tests of that gas
   are handed to the model a few at a time, and the error is read on tests of other days.

Needs pandas, numpy and scikit-learn (the engine's pinned versions), not Cantera: it reads the
committed flex_tests.json and the slider spans in flex_gaps.json. The replay fits a few thousand
small models and takes a few minutes. Run after the build has written the other files:

    uv run --python 3.12 --with-requirements pipeline/flame_temperature/requirements.txt \
        python pipeline/flame_temperature/doe.py

build.py calls the same ``write_outputs`` after the gap list.

Written with SI assistance (Claude Code).
"""

from __future__ import annotations

import datetime
import json
import math
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import fit  # noqa: E402
import gaps  # noqa: E402

REPO = Path(__file__).resolve().parent.parent.parent
OUT_DIR = REPO / "data/modules/flame-temperature"
SEED = 0
BOOTSTRAP_DRAWS = 2000
# For two repeats of one test that each scatter by s (normal), the median gap between them is
# 0.6745 * sqrt(2) * s.
MEDIAN_GAP_PER_SD = 0.6745 * math.sqrt(2.0)
SI_NOTE = (
    "Generated by pipeline/flame_temperature/doe.py, a script written with SI assistance "
    "(Claude Code, Anthropic). The humans chose the idea and the method."
)


# ---------------------------------------------------------------------------------------
# 1. Lack of fit: model error against the scatter between repeated tests
# ---------------------------------------------------------------------------------------
def lack_of_fit_numbers(residuals_points, pair_gaps_points, seed: int = SEED, draws: int = BOOTSTRAP_DRAWS) -> dict:
    """The comparison itself, from the model's misses and the gaps between repeated tests.

    Pure-error SD: sqrt(mean(gap^2) / 2), the scatter of one test estimated from pairs. The
    ratio is the model's root-mean-square error divided by it: 1 means the model is as good as
    the data allows, 2 means it misses by twice the scatter. The interval is a bootstrap over
    the tests and the pairs (both resampled)."""
    res = np.asarray(residuals_points, dtype=float)
    gap = np.asarray(pair_gaps_points, dtype=float)
    rmse = float(np.sqrt(np.mean(res ** 2)))
    sd = float(np.sqrt(np.mean(gap ** 2) / 2.0))
    sd_median = float(np.median(gap) / MEDIAN_GAP_PER_SD)
    rng = np.random.default_rng(seed)
    ratios = []
    for _ in range(draws):
        r = rng.choice(res, size=len(res), replace=True)
        g = rng.choice(gap, size=len(gap), replace=True)
        pure = np.sqrt(np.mean(g ** 2) / 2.0)
        if pure > 0:
            ratios.append(np.sqrt(np.mean(r ** 2)) / pure)
    lo, hi = np.percentile(ratios, [2.5, 97.5])
    return {
        "model_rmse_points": round(rmse, 1),
        "pure_error_sd_points": round(sd, 1),
        "pure_error_sd_from_median_points": round(sd_median, 1),
        "ratio": round(rmse / sd, 2),
        "ratio_from_median": round(rmse / sd_median, 2),
        "ratio_interval_95": [round(float(lo), 2), round(float(hi), 2)],
        "share_of_squared_error_that_is_scatter": round(min(1.0, (sd / rmse) ** 2), 2),
    }


def lack_of_fit(df) -> dict:
    """Check: the fitted link's error on unseen test days against the scatter of repeated tests.

    Same folds, seed and model as fit.fitted_link; same pairs as fit.repeatability."""
    d = fit.eligible_for_link(df)
    y = d["share_burned"]
    pred = fit._cv_predict(fit.model, d[fit.LINK_FEATURES], y, d["test_date"])
    residuals = (y.to_numpy() - pred) * 100.0
    gaps_points = fit.near_identical_gaps(df)
    numbers = lack_of_fit_numbers(residuals, gaps_points)
    return {
        "id": "lack_of_fit", "n_tests": len(d), "n_pairs": len(gaps_points),
        "method": f"model error from {fit.N_SPLITS}-fold cross-validation grouped by test day (seed {fit.SEED}, the "
                  "same folds as the check fitted_link); pure error from the near-identical pairs of the check "
                  "repeatability; ratio = model root-mean-square error / pure-error standard deviation; "
                  f"interval = bootstrap over tests and pairs, {BOOTSTRAP_DRAWS} draws, seed {SEED}",
        "definition_of_near_identical": fit.NEAR_IDENTICAL,
        "result": {
            "model_mean_abs_error_points": round(float(np.mean(np.abs(residuals))), 1),
            "median_points_apart": round(float(np.median(gaps_points)), 1),
            **numbers,
        },
        "note": "A ratio of 1 would mean the model is as good as the data allows. The pairs can share a test, "
                "so they are not independent and the interval is optimistic.",
        "passed": len(gaps_points) >= 10,
        "pass_rule": "at least 10 near-identical pairs, so the comparison means something (it is a yardstick, "
                     "not a bar the model has to clear)",
    }


# ---------------------------------------------------------------------------------------
# 2. Batch replay: does a designed batch teach the model faster than a one-by-one ranking?
# ---------------------------------------------------------------------------------------
REPLAY_SIZES = list(range(0, 31))  # tests handed back, for the batch and the ranking
REPLAY_RANDOM_SIZES = [0, 2, 4, 6, 8, 10, 15, 20, 25, 30]  # the sizes also scored for random picks
REPLAY_RANDOM_DRAWS = 20
REPLAY_FOLDS = 5
REPLAY_DEFAULT_TESTS = gaps.CAMPAIGN_DEFAULT_TESTS
# The groups of FLEX tests treated, one at a time, as "never flown": (id, plain name, rule).
REPLAY_REGIONS = [
    ("carbon_dioxide", "tests with carbon dioxide", lambda d: (d["gas_label"] == "with carbon dioxide").to_numpy()),
    ("helium", "tests with helium", lambda d: (d["gas_label"] == "with helium").to_numpy()),
    ("oxygen_21_and_above", "tests at 21% oxygen or more", lambda d: (d["x_o2"] >= 0.21 - 1e-9).to_numpy()),
]
REPLAY_METHOD = (
    "One group of FLEX tests is treated as never flown. The fitted link (same model and inputs as the "
    "check fitted_link) starts from all the other eligible tests. Tests of the group are then handed "
    "back k at a time, picked three ways: as a designed batch (greedy maximin, the method of the "
    "next-tests batch in flex_gaps.json), as the top k of a one-by-one ranking by distance to the "
    "starting tests, and at random. The error is the mean absolute error, in points of fuel burned, "
    f"on tests of the group from other test days ({REPLAY_FOLDS} folds grouped by test day: a test is "
    "never scored by a model that was handed a test of the same day). Distance: the gap list's own "
    "(oxygen, carbon dioxide, helium, pressure, each over its slider span)."
)


def scaled_points(d, spans: dict) -> np.ndarray:
    """The gap list's four axes, each divided by its slider span, so plain Euclidean distance
    between two rows equals gaps.distance."""
    return d[list(gaps.AXES)].to_numpy(dtype=float) / np.array([spans[k] for k in gaps.AXES])


def _gap_to(points: np.ndarray, base: list[int], cand: list[int]) -> np.ndarray:
    a, b = points[cand][:, None, :], points[base][None, :, :]
    return np.sqrt(((a - b) ** 2).sum(axis=2)).min(axis=1)


def batch_order(points: np.ndarray, base: list[int], cand: list[int]) -> list[int]:
    """The candidates in designed-batch order: each next one is the farthest from the starting
    tests plus the ones already taken (a tie goes to the earlier candidate). The first k of this
    order are the batch of k."""
    gap, out = _gap_to(points, base, cand), []
    for _ in range(len(cand)):
        j = int(np.argmax(np.round(gap, 9)))
        out.append(cand[j])
        gap = np.minimum(gap, np.sqrt(((points[cand] - points[cand[j]]) ** 2).sum(axis=1)))
        gap[j] = -1.0
    return out


def ranked_order(points: np.ndarray, base: list[int], cand: list[int]) -> list[int]:
    """The candidates as a one-by-one ranking: farthest from the starting tests first, each scored
    on its own (a tie goes to the earlier candidate)."""
    gap = _gap_to(points, base, cand)
    return [cand[j] for j in sorted(range(len(cand)), key=lambda j: (-round(float(gap[j]), 9), j))]


def replay(X, y, groups, points: np.ndarray, in_region: np.ndarray, make=None, sizes=None, random_sizes=None,
           draws: int = REPLAY_RANDOM_DRAWS, seed: int = SEED) -> dict:
    """One replay: the error on the region's tests after k of them are handed back, per way of
    picking. X, y, groups are the modelling table, target and test days of all eligible tests."""
    from sklearn.model_selection import GroupKFold

    make = make or fit.model
    sizes = list(REPLAY_SIZES if sizes is None else sizes)
    random_sizes = list(REPLAY_RANDOM_SIZES if random_sizes is None else random_sizes)
    region = np.flatnonzero(in_region)
    base = [int(i) for i in np.flatnonzero(~in_region)]
    folds = [([int(i) for i in region[tr]], region[te])
             for tr, te in GroupKFold(n_splits=REPLAY_FOLDS).split(region, None, groups.iloc[region])]
    sizes = [k for k in sizes if k <= min(len(cand) for cand, _ in folds)]
    random_sizes = [k for k in random_sizes if k in sizes]
    truth = y.to_numpy()[region]

    def error(orders: list[list[int]], k: int) -> float:
        pred = np.full(len(y), np.nan)
        for (_, held_out), order in zip(folds, orders):
            rows = base + order[:k]
            pred[held_out] = make().fit(X.iloc[rows], y.iloc[rows]).predict(X.iloc[held_out])
        return float(np.mean(np.abs(truth - pred[region]))) * 100.0

    batch = [batch_order(points, base, cand) for cand, _ in folds]
    ranked = [ranked_order(points, base, cand) for cand, _ in folds]
    rng = np.random.default_rng(seed)
    shuffles = [[[int(i) for i in rng.permutation(cand)] for cand, _ in folds] for _ in range(draws)]
    curve = []
    for k in sizes:
        row = {"tests": k, "batch": round(error(batch, k), 1), "ranked_list": round(error(ranked, k), 1)}
        if k in random_sizes and draws:
            r = [error(orders, k) for orders in shuffles]
            row.update(random_mean=round(float(np.mean(r)), 1), random_p10=round(float(np.percentile(r, 10)), 1),
                       random_p90=round(float(np.percentile(r, 90)), 1))
        curve.append(row)
    given = [c for c in curve if c["tests"] > 0]
    at = next((c for c in curve if c["tests"] == REPLAY_DEFAULT_TESTS), curve[-1])
    mean_batch = round(float(np.mean([c["batch"] for c in given])), 1)
    mean_ranked = round(float(np.mean([c["ranked_list"] for c in given])), 1)
    return {
        "n_region": int(len(region)), "n_start": len(base), "test_days": int(groups.iloc[region].nunique()),
        "candidates_per_fold": [len(cand) for cand, _ in folds],
        "curve": curve,
        "all_candidates_points": round(error([cand for cand, _ in folds], max(len(cand) for cand, _ in folds)), 1),
        "summary": {
            "none_handed_back_points": curve[0]["batch"],
            "at_default": at,
            "mean_over_sizes": {"sizes": f"{given[0]['tests']} to {given[-1]['tests']}", "batch": mean_batch,
                                "ranked_list": mean_ranked},
            "sizes_batch_ahead": sum(c["batch"] < c["ranked_list"] for c in given),
            "sizes_compared": len(given),
            "batch_ahead_of_ranked_list": mean_batch < mean_ranked,
        },
    }


def batch_replay(df, spans: dict, make=None, **kwargs) -> dict:
    """Check: the designed batch against a one-by-one ranking, replayed on tests already flown."""
    d = fit.eligible_for_link(df)
    X, y, groups = d[fit.LINK_FEATURES], d["share_burned"], d["test_date"]
    points = scaled_points(d, spans)
    replays = []
    for rid, name, rule in REPLAY_REGIONS:
        replays.append({"id": rid, "region": name, **replay(X, y, groups, points, rule(d), make=make, **kwargs)})
    ahead = [r["id"] for r in replays if r["summary"]["batch_ahead_of_ranked_list"]]
    return {
        "id": "batch_replay", "n_tests": len(d), "n_replays": len(replays),
        "method": REPLAY_METHOD,
        "sizes": "0 to 30 tests handed back; random picks scored at "
                 + ", ".join(str(k) for k in REPLAY_RANDOM_SIZES) + f" as the mean of {REPLAY_RANDOM_DRAWS} draws "
                 f"(seed {SEED}) with the 10th and 90th percentile",
        "result": {"replays": replays, "batch_ahead_in": ahead,
                   "batch_behind_in": [r["id"] for r in replays if r["id"] not in ahead]},
        "note": "The curves are noisy: a few tests more or less move the error by a point or two. Read the "
                "trend and the average over sizes, not one size. A replay says how the method did on tests "
                "that exist; it does not say what a flame would do in an untested gas.",
        "passed": len(ahead) > len(replays) / 2,
        "pass_rule": "averaged over the batch sizes, the designed batch leaves a lower error than the "
                     "one-by-one ranking in most replays",
    }


# ---------------------------------------------------------------------------------------
# flex_doe.json
# ---------------------------------------------------------------------------------------
def doe_doc(tests_doc: dict, spans: dict, date: str | None = None, commit: str | None = None) -> dict:
    df = fit.frame(tests_doc["tests"])
    checks = [lack_of_fit(df), batch_replay(df, spans)]
    return {
        "header": {
            "psi_ids": {"PSI-69": gaps.PSI_LINKS["PSI-69"]},
            "files": {"PSI-69": gaps.FLEX_FILE + " (read through flex_tests.json)"},
            "script": "pipeline/flame_temperature/doe.py (called by build.py)",
            "script_commit": commit or gaps._git_commit(),
            "date": date or datetime.date.today().isoformat(),
            "random_seed": SEED,
            "si_note": SI_NOTE,
            "what": "Design-of-experiments checks on the fitted link. Every number is computed by the script "
                    "from flex_tests.json; none is typed by hand.",
        },
        "checks": checks,
    }


def write_outputs(out_dir: Path = OUT_DIR) -> dict:
    tests_doc = json.loads((out_dir / "flex_tests.json").read_text(encoding="utf-8"))
    spans = json.loads((out_dir / "flex_gaps.json").read_text(encoding="utf-8"))["header"]["spans"]  # gaps.py
    doc = doe_doc(tests_doc, spans)
    (out_dir / "flex_doe.json").write_text(json.dumps(doc, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return {c["id"]: c["result"] for c in doc["checks"]}


def main() -> int:
    import handover

    for cid, result in write_outputs().items():
        print(f"{cid}: {json.dumps(result)[:300]}")
    counts = handover.write_all(OUT_DIR)
    print(f"wrote flex_doe.json, module.json, evidence.json ({counts['evidence']} records) and findings.json "
          f"({counts['findings']} records)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
