def diluted(r: dict) -> bool:
    return r["x_co2"] > ADDED_GAS_THRESHOLD or r["x_he"] > ADDED_GAS_THRESHOLD


def _near_region_pressure(p: float) -> bool:
    return abs(p - REGION_PRESSURE_ATM) <= REGION_PRESSURE_TOLERANCE_ATM


def coverage(tests: list[dict], cfi: list[dict], plan: dict) -> dict:
    """Counts over every per-test row as read (FLEX test 114 included: only its pressure is
    suspect, its gas fractions are read as written)."""
    fx = [{"test_id": t["test_id"], "x_o2": t["x_o2"], "x_co2": t["x_co2"], "x_he": t["x_he"],
           "pressure_atm": t["pressure_atm"]} for t in tests]
    f_dil = [r for r in fx if diluted(r)]
    f_co2 = [r for r in fx if r["x_co2"] > ADDED_GAS_THRESHOLD]
    f_he = [r for r in fx if r["x_he"] > ADDED_GAS_THRESHOLD]
    f_high = [r for r in fx if r["x_o2"] >= REGION_X_O2[0] - 1e-9]
    c_dil = [r for r in cfi if diluted(r)]
    c_he = [r for r in cfi if r["x_he"] > ADDED_GAS_THRESHOLD]
    max_f = max((r["x_o2"] for r in f_dil), default=None)
    max_c = max((r["x_o2"] for r in c_dil), default=None)
    max_all = max((v for v in (max_f, max_c) if v is not None), default=0.0)
    return {
        "diluted_rule": f"carbon dioxide or helium above {ADDED_GAS_THRESHOLD} mole fraction",
        "flex": {
            "rows": len(fx), "diluted_rows": len(f_dil), "carbon_dioxide_rows": len(f_co2),
            "helium_rows": len(f_he),
            "max_x_o2_diluted": max_f,
            "max_x_o2_carbon_dioxide": max((r["x_o2"] for r in f_co2), default=None),
            "max_x_o2_helium": max((r["x_o2"] for r in f_he), default=None),
            "tests_at_max_x_o2_diluted": [r["test_id"] for r in f_dil if r["x_o2"] == max_f],
            "rows_at_30_percent_oxygen_or_more": len(f_high),
            "of_which_diluted": sum(diluted(r) for r in f_high),
            "of_which_near_0_7_atm": sum(_near_region_pressure(r["pressure_atm"]) for r in f_high),
        },
        "cfi": {
            "rows": len(cfi), "distinct_test_numbers": len({r["number"] for r in cfi}),
            "carbon_dioxide_column": False, "diluted_rows": len(c_dil), "helium_rows": len(c_he),
            "oxygen_levels": sorted({r["x_o2"] for r in cfi}),
            "helium_levels": sorted({r["x_he"] for r in c_he}),
            "max_x_o2_diluted": max_c,
            "composition_incomplete": [r["test_id"] for r in cfi if not r["complete"]],
        },
        "flex2": plan,
        "max_x_o2_diluted_per_test": max_all,
        "diluted_rows_counted": len(f_dil) + len(c_dil),
    }


def headline_problems(cov: dict) -> list[str]:
    """Every way the tables contradict HEADLINE_TEXT; empty means the sentence holds."""
    p, f, c, f2 = [], cov["flex"], cov["cfi"], cov["flex2"]
    if cov["max_x_o2_diluted_per_test"] > HEADLINE_MAX_X_O2 + 1e-9:
        p.append(f"a diluted per-test row sits at {cov['max_x_o2_diluted_per_test']} oxygen")
    if f["max_x_o2_carbon_dioxide"] is not None and f["max_x_o2_carbon_dioxide"] > HEADLINE_MAX_X_O2 + 1e-9:
        p.append("FLEX has carbon dioxide above 25% oxygen")
    if c["carbon_dioxide_column"]:
        p.append("CFI has a carbon dioxide column")
    if f2["per_test_rows"]:
        p.append("FLEX-2 has a test-number column")
    if f2["carbon_dioxide"]:
        p.append("FLEX-2 mentions carbon dioxide")
    if not f2["helium"] or not f2["oxygen_levels"] or abs(max(f2["oxygen_levels"]) - HEADLINE_FLEX2_MAX_X_O2) > 1e-9:
        p.append("FLEX-2 does not list helium mixtures up to 30% oxygen")
    return p


