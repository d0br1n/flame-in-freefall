def read_table(path: Path) -> list[dict]:
    """Rows of a PSI table (cp1252) as {header: cell}, blank lines skipped."""
    with open(path, encoding="cp1252", newline="") as f:
        rows = list(csv.reader(f))
    headers = rows[0]
    return [dict(zip(headers, cells)) for cells in rows[1:] if any(c.strip() for c in cells)]


def _number(text: str) -> float | None:
    text = (text or "").strip().replace("atm", "").strip()
    try:
        return float(text)
    except ValueError:
        return None


def _numbers(text: str) -> list[float]:
    """'0.17; 0.21;0.25; 0.3' or '0.5; 1.0; ... or 3.0' -> the listed numbers."""
    out = []
    for part in (text or "").replace(" or ", ";").split(";"):
        v = _number(part)
        if v is not None:
            out.append(v)
    return out


def cfi_rows(raw: list[dict]) -> list[dict]:
    """CFI (PSI-39) per-test rows.

    Test ID as in the catalog: PSI-39/<Flex Number>, with #<data row> where the table repeats
    a number (it lists eight tests twice). The table has no carbon dioxide column, so carbon
    dioxide is 0. A row is ``complete`` when its fractions add up to 0.98 to 1.01.
    """
    counts: dict[str, int] = {}
    for r in raw:
        counts[r["Flex Number"].strip()] = counts.get(r["Flex Number"].strip(), 0) + 1
    out = []
    for i, r in enumerate(raw, start=1):
        number = r["Flex Number"].strip()
        x = {"x_o2": _number(r["Oxygen"]), "x_n2": _number(r["Nitrogen"]), "x_he": _number(r["Helium"])}
        total = sum(v for v in x.values() if v is not None)
        out.append({
            "test_id": f"PSI-39/{number}" + (f"#{i}" if counts[number] > 1 else ""),
            "psi_id": "PSI-39", "number": int(number), "row": i, "fuel": r["Fuel "].strip(),
            **x, "x_co2": 0.0, "pressure_atm": _number(r["Pressure"]),
            "composition_sum": round(total, 4),
            "complete": None not in x.values() and _number(r["Pressure"]) is not None
            and COMPOSITION_SUM_RANGE[0] <= total <= COMPOSITION_SUM_RANGE[1],
        })
    return out


def flex2_plan(raw: list[dict]) -> dict:
    """FLEX-2 (PSI-68): what its table lists. It is a planned range per fuel, not tests."""
    headers = list(raw[0]) if raw else []
    test_column = [h for h in headers if "test" in h.lower() or "number" in h.lower() or "#" in h]
    oxygen = sorted({v for r in raw for v in _numbers(r["Oxygen Mole Fraction"])})
    pressure = sorted({v for r in raw for v in _numbers(r["Ambient Pressure (atm)"])})
    mixtures = sorted({r["Ambient Gas Mixture "].strip() for r in raw})
    text = " ".join(" ".join(r.values()) for r in raw)
    return {
        "rows": len(raw),
        "per_test_rows": bool(test_column),
        "fuels": [r["Sample (Fuel Type)"].strip() for r in raw],
        "gas_mixtures": mixtures,
        "oxygen_levels": oxygen,
        "pressures_atm": pressure,
        "helium": any("He" in m for m in mixtures),
        "carbon_dioxide": "CO2" in text or "arbon" in text,
    }


def flex_rows(tests: list[dict]) -> list[dict]:
    """FLEX (PSI-69) usable tests from flex_tests.json (test 114, pressure 0, is left out)."""
    return [{"test_id": t["test_id"], "psi_id": "PSI-69", "number": t["flex_test"], "row": 0,
             "fuel": t["fuel"], "x_o2": t["x_o2"], "x_co2": t["x_co2"], "x_he": t["x_he"],
             "pressure_atm": t["pressure_atm"]}
            for t in tests if not t["flags"]["dropped"]]


