# The designed batch: next tests chosen as a set (DOB-114)
# ---------------------------------------------------------------------------------------
CAMPAIGN_PICKS = 12  # picks written to the file; the first k of them are the batch of k tests
CAMPAIGN_DEFAULT_TESTS = 6  # the batch size the page and the headline show first
CAMPAIGN_METHOD = (
    "Design augmentation by greedy maximin distance (Johnson, Moore and Ylvisaker 1990): take the "
    "condition farthest from every real test, count it as flown, then take the condition farthest "
    "from the real tests and the earlier picks together, and repeat. Same distance and spans as "
    "the gap list. No model is used and nothing is predicted."
)
CAMPAIGN_WHY = (
    "The ranked list scores each condition on its own, so its top rows are near-copies of one "
    "corner. Once the first of them is flown the others are no longer far from a test. The batch "
    "takes each earlier pick into account, so its tests spread over the region."
)
CAMPAIGN_FUEL = (
    "Fuel and droplet size are not part of the distance, so a pick is a gas condition. Which fuel "
    "to burn at it is left open."
)
CAMPAIGN_CURVE = (
    "For 0 to n tests flown: the largest and the mean distance from a condition in the region to "
    "its nearest test, real or flown from the plan. designed_batch flies the picks in order; "
    "ranked_list flies the first distinct gas conditions of the ranked list."
)


def _point(row: dict) -> dict:
    """The four distance axes of a gap row or a pick."""
    return {"x_o2": row["x_o2"], "x_co2": row["x_added"] if row["added_gas"] == "carbon dioxide" else 0.0,
            "x_he": row["x_added"] if row["added_gas"] == "helium" else 0.0, "pressure_atm": row["pressure_atm"]}


def campaign(rows: list[dict], refs: list[dict], spans: dict, n: int = CAMPAIGN_PICKS) -> dict:
    """The next n tests as one batch, and how the region's largest gap falls as they are flown.

    ``rows`` are the ranked gap rows (one per fuel); the batch works on their distinct gas
    conditions, in rank order. Each pick is the condition with the largest distance to the real
    tests plus the picks before it; a tie goes to the condition ranked higher in the gap list.
    It stops early when every condition sits on a test. The same walk over the ranked list
    gives the comparison curve."""
    conditions, seen = [], set()
    for r in sorted(rows, key=lambda r: r["rank"]):
        key = (r["added_gas"], r["x_added"], r["x_o2"], r["pressure_atm"])
        if key not in seen:
            seen.add(key)
            conditions.append(r)
    points = [_point(r) for r in conditions]
    to_real = [min(distance(p, ref, spans) for ref in refs) for p in points]

    def fly(gap: list[float], j: int) -> list[float]:
        return [min(g, distance(p, points[j], spans)) for g, p in zip(gap, points)]

    def stats(gap: list[float]) -> tuple[float, float]:
        return round(max(gap), 3), round(sum(gap) / len(gap), 3)

    gap, picks, designed = list(to_real), [], [stats(to_real)]
    for step in range(1, n + 1):
        j = max(range(len(points)), key=lambda i: (round(gap[i], 9), -i))
        if gap[j] <= 1e-9:
            break
        c, near = conditions[j], nearest(points[j], refs, spans)[0]
        when_picked = gap[j]
        gap = fly(gap, j)
        designed.append(stats(gap))
        picks.append({
            "pick": step, "added_gas": c["added_gas"], "x_added": c["x_added"], "x_o2": c["x_o2"],
            "x_n2": c["x_n2"], "pressure_atm": c["pressure_atm"],
            "gap_when_picked": round(when_picked, 3),
            "largest_gap_after": designed[-1][0], "mean_gap_after": designed[-1][1],
            "nearest_test_id": near["test_id"], "nearest_conditions": _conditions(near),
            "differs_by": {k: round(points[j][k] - near[k], 4) for k in AXES},
            "model_fails_here": c["model_fails_here"], "note": c["note"],
        })

    gap, listed = list(to_real), [stats(to_real)]
    for j in range(min(len(picks), len(points))):
        gap = fly(gap, j)
        listed.append(stats(gap))

    return {
        "method": CAMPAIGN_METHOD, "why": CAMPAIGN_WHY, "fuel": CAMPAIGN_FUEL,
        "not_a_prediction": NOT_A_PREDICTION,
        "n_conditions": len(conditions),
        "conditions": "the distinct gas conditions of the rows below (fuel collapsed)",
        "default_tests": min(CAMPAIGN_DEFAULT_TESTS, len(picks)),
        "picks": picks,
        "curve_columns": CAMPAIGN_CURVE,
        "curve": [{"tests": k, "designed_batch": d[0], "ranked_list": r[0],
                   "designed_batch_mean": d[1], "ranked_list_mean": r[1]}
                  for k, (d, r) in enumerate(zip(designed, listed))],
    }


