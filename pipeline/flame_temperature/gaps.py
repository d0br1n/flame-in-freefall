def grid_cells(grid_doc: dict) -> list[dict]:
    """The grid's gas positions as dicts (one per fuel, gas and pressure; droplet size dropped)."""
    cols = grid_doc["header"]["columns"]
    i = {k: cols.index(k) for k in ("fuel", "x_o2", "added_gas", "x_added", "pressure_atm")}
    seen, out = set(), []
    for row in grid_doc["rows"]:
        key = tuple(row[i[k]] for k in ("fuel", "added_gas", "x_added", "x_o2", "pressure_atm"))
        if key in seen:
            continue
        seen.add(key)
        fuel, gas, x, o2, p = key
        out.append({"fuel": fuel, "added_gas": gas, "x_added": x, "x_o2": o2, "pressure_atm": p,
                    "x_co2": x if gas == "carbon dioxide" else 0.0,
                    "x_he": x if gas == "helium" else 0.0,
                    "x_n2": round(1.0 - o2 - x, 4)})
    return out


def axis_spans(cells: list[dict]) -> dict:
    """Width of the bench's slider range on each axis, read from the grid itself."""
    return {k: round(max(c[k] for c in cells) - min(c[k] for c in cells), 6) for k in AXES}


def distance(a: dict, b: dict, spans: dict) -> float:
    """sqrt(sum over oxygen, carbon dioxide, helium and pressure of ((a - b) / span)^2).

    Each axis is divided by the width of its slider range, so no unit dominates: 1.0 is as far
    as one whole slider. Fuel and droplet size are not part of it."""
    return math.sqrt(sum(((a[k] - b[k]) / spans[k]) ** 2 for k in AXES))


def nearest(cell: dict, refs: list[dict], spans: dict) -> tuple[dict, float]:
    """The closest real row. Ties go to FLEX before CFI, then the lower test number."""
    order = {"PSI-69": 0, "PSI-39": 1}
    best = min(refs, key=lambda r: (round(distance(cell, r, spans), 9), order[r["psi_id"]],
                                    r["number"], r["row"]))
    return best, distance(cell, best, spans)


def in_region(cell: dict) -> bool:
    return (REGION_X_O2[0] - 1e-9 <= cell["x_o2"] <= REGION_X_O2[1] + 1e-9
            and abs(cell["pressure_atm"] - REGION_PRESSURE_ATM) < 1e-9)


def note_for(cell: dict, cov: dict, refs: list[dict]) -> str:
    """The plain note for a gap cell. Each claim is checked against the tables first."""
    f2 = cov["flex2"]
    if cell["added_gas"] == "carbon dioxide":
        tested = [r for r in refs if r["x_co2"] > ADDED_GAS_THRESHOLD and r["x_o2"] >= REGION_X_O2[0] - 1e-9]
        assert not tested and not f2["carbon_dioxide"], "carbon dioxide was tested at 30% oxygen or more"
        return NOTE_CO2
    if cell["added_gas"] == "helium":
        tested = [r for r in refs if r["x_he"] > ADDED_GAS_THRESHOLD and r["x_o2"] >= REGION_X_O2[0] - 1e-9]
        assert not tested, "helium was tested at 30% oxygen or more"
        if f2["helium"] and any(abs(cell["x_o2"] - o) < 1e-9 for o in f2["oxygen_levels"]):
            return NOTE_HE_FLEX2
        return NOTE_HE_ABOVE_PLAN.format(plan_max=max(f2["oxygen_levels"]) * 100)
    levels = sorted({r["x_o2"] for r in refs if r["psi_id"] == "PSI-69" and not diluted(r)
                     and REGION_X_O2[0] - 1e-9 <= r["x_o2"] <= REGION_X_O2[1] + 1e-9
                     and _near_region_pressure(r["pressure_atm"])})
    return NOTE_N2.format(levels=" and ".join(f"{v * 100:.0f}%" for v in levels) or "no")


def _conditions(r: dict) -> dict:
    return {"fuel": r["fuel"], "x_o2": r["x_o2"], "x_co2": r["x_co2"], "x_he": r["x_he"],
            "pressure_atm": r["pressure_atm"]}


def gap_rows(cells: list[dict], refs: list[dict], spans: dict, cov: dict) -> list[dict]:
    """Region cells ranked by distance to the nearest real test, largest gap first."""
    flex = [r for r in refs if r["psi_id"] == "PSI-69"]
    rows = []
    for c in cells:
        if not in_region(c):
            continue
        near, d = nearest(c, refs, spans)
        same, d_same = nearest(c, [r for r in flex if r["fuel"] == c["fuel"]], spans)
        rows.append({
            "fuel": c["fuel"], "added_gas": c["added_gas"], "x_added": c["x_added"],
            "x_o2": c["x_o2"], "x_n2": c["x_n2"], "pressure_atm": c["pressure_atm"],
            "distance": round(d, 3),
            "nearest_test_id": near["test_id"], "nearest_conditions": _conditions(near),
            "distance_same_fuel": round(d_same, 3),
            "nearest_same_fuel_test_id": same["test_id"],
            "model_fails_here": c["added_gas"] == "helium",
            "note": note_for(c, cov, refs),
        })
    gas_order = {"carbon dioxide": 0, "helium": 1, "none": 2}
    rows.sort(key=lambda r: (-r["distance"], -r["distance_same_fuel"], gas_order[r["added_gas"]],
                             -r["x_added"], r["x_o2"], r["fuel"]))
    for i, r in enumerate(rows, start=1):
        r["rank"] = i
    return [{"rank": r.pop("rank"), **r} for r in rows]


