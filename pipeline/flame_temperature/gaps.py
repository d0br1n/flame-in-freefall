def _git_commit() -> str:
    try:
        sha = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=REPO, capture_output=True,
                             text=True, check=True).stdout.strip()
        dirty = subprocess.run(["git", "status", "--porcelain", "pipeline"], cwd=REPO,
                               capture_output=True, text=True, check=True).stdout.strip()
        return sha + ("+local" if dirty else "")
    except Exception:
        return "unknown"


def gaps_doc(tests_doc: dict, grid_doc: dict, checks_doc: dict, cfi: list[dict], plan: dict,
             date: str | None = None, commit: str | None = None) -> dict:
    tests = tests_doc["tests"]
    cov = coverage(tests, cfi, plan)
    problems = headline_problems(cov)
    cells = grid_cells(grid_doc)
    spans = axis_spans(cells)
    refs = flex_rows(tests) + [r for r in cfi if r["complete"]]
    rows = gap_rows(cells, refs, spans, cov)
    left_out = [{"test_id": r["test_id"], "reason": "composition incomplete: oxygen "
                 f"{r['x_o2']}, nitrogen {r['x_n2']}, helium {r['x_he']} add up to {r['composition_sum']}"}
                for r in cfi if not r["complete"]]
    left_out += [{"test_id": t["test_id"], "reason": t["dropped_reason"] or "dropped"}
                 for t in tests if t["flags"]["dropped"]]
    return {
        "header": {
            "psi_ids": PSI_LINKS,
            "files": {"PSI-69": FLEX_FILE + " (read through flex_tests.json)", "PSI-39": CFI_FILE,
                      "PSI-68": FLEX2_FILE},
            "script": "pipeline/flame_temperature/gaps.py (called by build.py)",
            "script_commit": commit or _git_commit(),
            "date": date or datetime.date.today().isoformat(),
            "si_note": SI_NOTE,
            "scope": SCOPE,
            "not_a_prediction": NOT_A_PREDICTION,
            "region": REGION_TEXT,
            "region_cells": "every grid position with oxygen 0.30 to 0.34 and pressure 0.7 atm, "
                            "one row per fuel, added gas and level (droplet size is not part of a cell)",
            "distance": "sqrt(sum over oxygen, carbon dioxide and helium mole fraction and pressure "
                        "in atm of ((cell - test) / span)^2). Each span is the width of the bench's "
                        "slider range on that axis, read from flex_grid.json, so 1.0 is as far as one "
                        "whole slider. Fuel and droplet size are not part of it. 0 means a real test "
                        "sits at exactly these gas conditions.",
            "spans": spans,
            "nearest_test_id": "the closest real per-test row in FLEX (PSI-69) or CFI (PSI-39), any "
                               "fuel; ties go to FLEX, then the lower test number",
            "nearest_same_fuel_test_id": "the closest FLEX test of the cell's fuel (CFI burned other "
                                         "fuels), with its distance in distance_same_fuel",
            "ranking": "distance, largest first; then distance_same_fuel, largest first",
            "model_fails_here": "true for helium cells; see model_fails_here in flex_grid.json's header",
            "reference_rows": {"PSI-69": sum(r["psi_id"] == "PSI-69" for r in refs),
                               "PSI-39": sum(r["psi_id"] == "PSI-39" for r in refs)},
            "left_out": left_out,
            "cfi_carbon_dioxide": "CFI lists only oxygen, nitrogen and helium, so its carbon dioxide is 0",
            "flex2": "FLEX-2 (PSI-68) holds no per-test rows, only a planned range, so it gives no "
                     "nearest test; it is used only for the notes",
            "coverage": cov,
            "headline": HEADLINE_TEXT,
            "headline_holds": not problems,
            "headline_problems": problems,
            "n_rows": len(rows),
            "campaign": campaign(rows, refs, spans),
        },
        "rows": rows,
    }


def write_outputs(out_dir: Path = OUT_DIR, tables_dir: Path = TABLES) -> dict:
    """Read the committed engine files and the two tables, write flex_gaps.json and add the
    helium column to flex_grid.json. Stops (ValueError) if the tables contradict the headline."""
    missing = [n for n in (CFI_FILE, FLEX2_FILE) if not (tables_dir / n).is_file()]
    if missing:
        raise FileNotFoundError(f"missing PSI table(s) in {tables_dir}: {missing}")
    tests_doc, grid_doc, checks_doc = (json.loads((out_dir / n).read_text(encoding="utf-8"))
                                       for n in ("flex_tests.json", "flex_grid.json", "flex_checks.json"))
    cfi = cfi_rows(read_table(tables_dir / CFI_FILE))
    plan = flex2_plan(read_table(tables_dir / FLEX2_FILE))
    doc = gaps_doc(tests_doc, grid_doc, checks_doc, cfi, plan)
    if not doc["header"]["headline_holds"]:
        raise ValueError("the PSI tables contradict the headline: " + "; ".join(doc["header"]["headline_problems"]))
    (out_dir / "flex_gaps.json").write_text(json.dumps(doc, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    n_flagged = add_helium_flag(grid_doc, checks_doc)
    path = out_dir / "flex_grid.json"
    path.write_text(json.dumps(grid_doc, separators=(",", ":"), ensure_ascii=False) + "\n", encoding="utf-8")
    assert path.stat().st_size < 3 * 1024 * 1024, "flex_grid.json is over 3 MB"
    return {"gap_rows": doc["header"]["n_rows"], "grid_flagged": n_flagged,
            "coverage": doc["header"]["coverage"]}


