def helium_flag(checks_doc: dict) -> dict:
    """The flag text, with both R2 values read from the carry_over_helium check."""
    c = next(c for c in checks_doc["checks"] if c["id"] == "carry_over_helium")
    t, b = c["result"]["temperature_only"]["r2"], c["result"]["both_numbers"]["r2"]
    return {
        "label": FLAG_LABEL,
        "text": FLAG_TEXT.format(t=t, b=b),
        "applies_to": "every row whose added_gas is helium",
        "r2_temperature_only": t,
        "r2_with_transport": b,
        "n_helium_tests": c["n_test"],
        "source": "flex_checks.json, check carry_over_helium (straight line trained on tests "
                  "without helium, scored on the methanol helium tests; the transport term is "
                  "the heat-spreading speed)",
    }


def add_helium_flag(grid_doc: dict, checks_doc: dict) -> int:
    """Append the boolean column model_fails_here (true for helium rows) to every grid row.

    Existing columns keep their positions; running it twice changes nothing."""
    header = grid_doc["header"]
    cols = header["columns"]
    gas = cols.index("added_gas")
    if "model_fails_here" not in cols:
        cols.append("model_fails_here")
        for row in grid_doc["rows"]:
            row.append(None)
    k = cols.index("model_fails_here")
    for row in grid_doc["rows"]:
        row[k] = row[gas] == "helium"
    header["model_fails_here"] = {"column": k, **helium_flag(checks_doc),
                                  "added_by": "pipeline/flame_temperature/gaps.py"}
    return sum(row[k] for row in grid_doc["rows"])


